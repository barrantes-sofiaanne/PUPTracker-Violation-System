<?php

namespace App\Services;

use App\Models\ViolationEvidence;
use App\Support\Storage\EvidenceDisk;

/**
 * Evidence storage + integrity helpers.
 *
 * The browser/camera is responsible for baking the visible PUPTracker
 * evidence watermark into captured images.
 *
 * This service DOES NOT add another visible watermark to the image.
 *
 * The final uploaded image is stored byte-for-byte as received from the
 * browser. This prevents the old GD-generated pixel-style watermark from
 * being added on top of the camera watermark.
 *
 * The service still provides:
 * - private evidence storage
 * - SHA-256 integrity hashing
 * - auxiliary verification marker
 *
 * The Evidence ID remains a database/storage identifier and is not
 * physically stamped onto the photograph by this service.
 */
class EvidenceWatermarkService
{
    /**
     * Compute the SHA-256 hash of the final stored bytes.
     */
    public function sha256(string $bytes): string
    {
        return hash('sha256', $bytes);
    }

    /**
     * Persist an auxiliary verification marker next to the image.
     *
     * The marker contains:
     * - evidence code
     * - SHA-256 of a random verification token
     * - creation timestamp
     *
     * No additional visible watermark is added to the image.
     */
    public function storeVerificationMarker(
        string $diskPath,
        string $evidenceCode,
        string $token,
    ): string {
        $marker = json_encode([
            'schema' => 'puptracker-evidence-marker-v1',
            'evidence_code' => $evidenceCode,
            'token_sha256' => hash('sha256', $token),
            'created_at' => now()->toIso8601String(),
        ], JSON_UNESCAPED_SLASHES);

        $disk = EvidenceDisk::disk();

        $markerPath = $diskPath . '.marker.json';

        $disk->put($markerPath, $marker);

        return $markerPath;
    }

    /**
     * Prepare image evidence without modifying the image.
     *
     * IMPORTANT:
     * The browser-generated PUPTracker camera watermark is already baked
     * into the uploaded image. Therefore, this method intentionally returns
     * the original bytes unchanged.
     */
    public function prepareImageEvidence(
        ViolationEvidence $evidence,
        string $imageBytes,
        ?string $capturedAt = null,
    ): array {
        return [
            'bytes' => $imageBytes,
            'watermarked' => false,
            'sha256' => $this->sha256($imageBytes),
        ];
    }

    /**
     * Store the official evidence file on the private evidence disk.
     *
     * The uploaded image is stored AS-IS.
     *
     * The previous implementation re-encoded JPG/PNG files with GD and
     * added this server-side pixel-style overlay:
     *
     *   PUPTracker
     *   Evidence ID: EVD-YYYY-NNNNNN
     *   Student ID: ...
     *   Captured: ...
     *
     * That behavior has intentionally been removed.
     *
     * The professional watermark generated by the camera remains part of
     * the uploaded image.
     *
     * @return array{
     *     path:string,
     *     sha256:string,
     *     server_watermarked:bool,
     *     marker_path:?string
     * }
     */
    public function storeOfficialFile(
        $file,
        string $directory,
        string $filename,
        string $evidenceCode,
        string $studentNumber,
        ?string $capturedAt = null,
    ): array {
        /*
         * Make sure evidence storage is properly configured and writable.
         */
        EvidenceDisk::assertWritable();

        $disk = EvidenceDisk::disk();

        /*
         * Read the uploaded file exactly as received.
         */
        $originalBytes = method_exists($file, 'getContent')
            ? (string) $file->getContent()
            : (string) file_get_contents($file);

        /*
         * Do NOT process the image through GD.
         *
         * This preserves:
         * - the camera-generated PUPTracker watermark
         * - face blurring already performed in the browser
         * - original JPEG encoding
         * - original image pixels
         */
        $finalBytes = $originalBytes;

        $relative = $directory . '/' . $filename;

        /*
         * Store the exact uploaded bytes.
         */
        $disk->put($relative, $finalBytes);

        /*
         * Hash the exact bytes that were stored.
         */
        $sha256 = $this->sha256($finalBytes);

        /*
         * Keep the auxiliary verification marker.
         *
         * This does NOT modify the photograph.
         */
        $token = bin2hex(random_bytes(16));

        $markerPath = $this->storeVerificationMarker(
            $relative,
            $evidenceCode,
            $token
        );

        return [
            'path' => $relative,
            'sha256' => $sha256,
            'server_watermarked' => false,
            'marker_path' => $markerPath,
        ];
    }
}